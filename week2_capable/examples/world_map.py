"""Build the world map from sessions.db — Layer 3.

    python examples/ingest_sessions.py      # first, to (re)build the database
    python examples/world_map.py            # writes docs/maps/world.md + .dot

Free: reads only what is already on disk.

Mermaid is the primary output because GitHub renders it natively — the map can
be dropped into a README with no toolchain and no image file. Graphviz DOT is
written alongside for anyone with `dot` installed (it is not, here).
"""

import json
import os
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from boukensha import world  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
BOUKENSHA_DIR = Path(os.environ.get("BOUKENSHA_DIR") or REPO_ROOT / ".boukensha")
DB = BOUKENSHA_DIR / "sessions.db"
OUT_DIR = REPO_ROOT / "docs" / "maps"


def load_sessions():
    """Journey events grouped by session, ordered as they happened.

    Ordering is by (seq) within a session, which is the line number in the
    source .jsonl — the order the events were written, which is the order they
    occurred. Sessions stay separate because the "where am I" cursor cannot
    cross a reconnect.
    """
    db = sqlite3.connect(DB)
    rows = db.execute(
        "SELECT session_id, raw FROM events WHERE phase LIKE 'journey.%' "
        "ORDER BY session_id, seq, id"
    ).fetchall()

    grouped = defaultdict(list)
    for session_id, raw in rows:
        grouped[session_id].append(json.loads(raw))
    return list(grouped.values())


def main():
    if not DB.exists():
        sys.exit(f"no database at {DB} — run examples/ingest_sessions.py first")

    sessions = load_sessions()
    graph = world.build(sessions)
    gaps = world.unexplored(graph)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    mermaid = world.to_mermaid(graph)
    (OUT_DIR / "world.dot").write_text(world.to_dot(graph))

    blocked_lines = []
    for block in graph["blocked"]:
        title = graph["rooms"].get(block["room"], {}).get("title", block["room"])
        blocked_lines.append(
            f"| {title} | {block['direction'] or '?'} | {block['reason']} |"
        )

    gap_lines = []
    for node, missing in sorted(gaps.items(), key=lambda kv: -len(kv[1]))[:15]:
        title = graph["rooms"][node]["title"]
        gap_lines.append(f"| {title} | {', '.join(missing)} |")

    doc = f"""# World map

Generated by `week2_capable/examples/world_map.py` from
`.boukensha/sessions.db`. Do not hand-edit — rerun the ingest and this script.

**{len(graph['rooms'])} rooms, {len(graph['edges'])} passages,
{len(graph['blocked'])} blocks** across {len(sessions)} sessions.

Rooms are identified by title *and* exit set, because the corpus contains three
titles covering more than one room — see `boukensha/world.py` for why title
alone is not an identity. Rounded nodes are unlit rooms, which the game will not
describe; dashed arrows are movements the game refused.

```mermaid
{mermaid}
```

## Where players get blocked

| Room | Direction | Reason |
| --- | --- | --- |
{chr(10).join(blocked_lines) if blocked_lines else '| (none) | | |'}

## Advertised exits never taken

The gap between what the game offers and where the agent went — the map's
coverage measure, and the first place to look before claiming a region is
unreachable rather than merely unvisited.

| Room | Untaken exits |
| --- | --- |
{chr(10).join(gap_lines) if gap_lines else '| (none) | |'}
"""

    (OUT_DIR / "world.md").write_text(doc)

    print(f"{len(graph['rooms'])} rooms, {len(graph['edges'])} passages, "
          f"{len(graph['blocked'])} blocks, {len(sessions)} sessions")
    print(f"unexplored exits in {len(gaps)} rooms")
    print(f"wrote {OUT_DIR / 'world.md'}")
    print(f"wrote {OUT_DIR / 'world.dot'}")


if __name__ == "__main__":
    main()
